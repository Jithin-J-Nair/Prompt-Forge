/** Resolve the effective preview for a module (override → subcategory default). */
export function resolvePreview(module: PromptModule | undefined | null): PreviewDefinition | null {
  if (!module) return null;
  if (module.preview) return module.preview;
  const direct = PREVIEW_MAP[module.id];
  if (direct) return direct;
  const fallback = SUB_DEFAULTS[`${module.category}/${module.subcategory}`];
  return fallback ?? null;
}

/** modules that fail preview resolution (should be empty — asserted by tests) */
export function unresolvedPreviewModules(modules: readonly PromptModule[]): string[] {
  return modules.filter((m) => !resolvePreview(m)).map((m) => m.id);
}
