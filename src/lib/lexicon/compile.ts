import { LEXICON_MAP, type Keyword, type Artifact, ARTIFACTS } from "./index";
import { MODULE_MAP } from "@/lib/studio";

export type ExportTarget = "raw" | "v0" | "cursor" | "claude";

export const EXPORT_TARGETS: { id: ExportTarget; label: string; hint: string }[] = [
  { id: "raw", label: "Raw Spec", hint: "Structured build spec, tool-agnostic" },
  { id: "v0", label: "v0 / Vercel", hint: "Imperative Next.js + Tailwind brief" },
  { id: "cursor", label: "Cursor", hint: "Rules-file style, terse and enforced" },
  { id: "claude", label: "Claude", hint: "XML-sectioned design directive" },
];

export function resolveStack(ids: string[]): Keyword[] {
  return ids.map((id) => LEXICON_MAP.get(id)).filter((k): k is Keyword => !!k);
}

function groupByFam(stack: Keyword[]): [string, Keyword[]][] {
  const m = new Map<string, Keyword[]>();
  for (const k of stack) {
    const arr = m.get(k.fam) ?? [];
    arr.push(k);
    m.set(k.fam, arr);
  }
  return [...m.entries()];
}


/* ---------------- P3/P4: realism + budget surfacing ---------------- */

interface ChipConflict { a: string; b: string; reason: string }

/** conflicts between module-backed chips currently in the stack */
export function stackConflicts(ids: string[]): ChipConflict[] {
  const mods = resolveStack(ids)
    .map((k) => (k.module ? MODULE_MAP.get(k.module) : undefined))
    .filter((m): m is NonNullable<typeof m> => !!m);
  const have = new Set(mods.map((m) => m.id));
  const seen = new Set<string>();
  const out: ChipConflict[] = [];
  for (const m of mods) {
    for (const edge of m.conflicts ?? []) {
      if (!have.has(edge.id)) continue;
      const key = [m.id, edge.id].sort().join("|");
      if (seen.has(key)) continue;
      seen.add(key);
      out.push({ a: m.name, b: MODULE_MAP.get(edge.id)?.name ?? edge.id, reason: edge.reason });
    }
  }
  return out;
}

/** registry-declared performance load of the stack */
export function stackBudget(ids: string[]): { heavy: string[]; medium: string[]; light: number } {
  const heavy: string[] = [];
  const medium: string[] = [];
  let light = 0;
  for (const k of resolveStack(ids)) {
    if (!k.module) continue;
    const m = MODULE_MAP.get(k.module);
    if (!m) continue;
    if (m.perf === "heavy") heavy.push(m.name);
    else if (m.perf === "medium") medium.push(m.name);
    else light += 1;
  }
  return { heavy, medium, light };
}

function realismPreamble(ids: string[]): string {
  const conflicts = stackConflicts(ids);
  const budget = stackBudget(ids);
  const lines: string[] = [];
  if (budget.heavy.length || budget.medium.length) {
    lines.push(
      `PERFORMANCE BUDGET — ${budget.heavy.length} heavy (${budget.heavy.join(", ") || "none"}), ${budget.medium.length} medium. Deliberately assign each heavy technique to ONE moment of the experience; never run two heavy renderers simultaneously.`,
    );
  }
  for (const c of conflicts) {
    lines.push(`CONFLICT — ${c.a} × ${c.b}: ${c.reason} Choose one, or assign them to different scroll scenes.`);
  }
  return lines.length ? lines.join("\n") + "\n\n" : "";
}

export function compileStack(ids: string[], target: ExportTarget, project = "the site"): string {
  const stack = resolveStack(ids);
  if (!stack.length) return "";
  const groups = groupByFam(stack);

  switch (target) {
    case "v0": {
      const lines = stack.map((k) => `- ${k.name}: ${k.phrase}`);
      return [
        `Build ${project} as a production Next.js (App Router) + Tailwind CSS application.`,
        ``,
        realismPreamble(ids) ? realismPreamble(ids).trimEnd() : `​`,
        `Implement every directive below exactly; each is non-negotiable:`,
        ``,
        ...lines,
        ``,
        `Constraints: no default purple gradients, no stock blobs, every interactive element has hover/press/focus states, prefers-reduced-motion respected, mobile fully responsive.`,
      ].join("\n");
    }
    case "cursor": {
      const rules = stack.map((k, i) => `RULE ${String(i + 1).padStart(2, "0")} // ${k.name}\n${k.phrase}`);
      return [
        `# ${project} — enforced design rules (${stack.length} chips)`,
        `# Generated by PromptForge Lexicon. Every rule below SHOULD block review until met.`,
        ``,
        realismPreamble(ids) ? realismPreamble(ids).trimEnd() : `​`,
        ...rules,
      ].join("\n\n");
    }
    case "claude": {
      const sections = groups
        .map(
          ([fam, ks]) =>
            `<${fam.toLowerCase().replace(/[^a-z0-9]+/g, "-")}>\n${ks.map((k) => `  <directive name="${k.name}">${k.phrase}</directive>`).join("\n")}\n</${fam.toLowerCase().replace(/[^a-z0-9]+/g, "-")}>`,
        )
        .join("\n\n");
      return [
        `<design-directive project="${project}">`,
        `<role>Senior creative engineer implementing an award-calibre website.</role>`,
        realismPreamble(ids) ? `<realism>\n${realismPreamble(ids)}</realism>` : `​`,
        sections,
        ``,
        `<quality-bar>Every directive renders in the final UI. Transforms and opacity only for motion. Focus states and reduced-motion fallbacks are mandatory.</quality-bar>`,
        `</design-directive>`,
      ].join("\n");
    }
    default: {
      const sections = groups
        .map(
          ([fam, ks]) =>
            `## ${fam}\n\n${ks.map((k) => `**${k.name}** — ${k.phrase}`).join("\n\n")}`,
        )
        .join("\n\n");
      return [
        `# ${project} — PromptForge compilation`,
        `_Stack: ${stack.length} keywords across ${groups.length} families._`,
        ``,
        realismPreamble(ids) ? `> ${realismPreamble(ids).trimEnd().replace(/\n/g, "\n> ")}` : `​`,
        sections,
        ``,
        `---`,
        `Accessibility: prefers-reduced-motion honoured for every kinetic directive; keyboard focus rings deliberate; contrast AA minimum.`,
        `Performance: heavy renderers lazy-load; static content prerenders.`,
      ].join("\n");
    }
  }
}

/* ------------------------- stack ↔ URL encoding ------------------------- */
/*  ids are stable strings; encode as an index-compressed base36 list.   */

const ID_INDEX: string[] = [...LEXICON_MAP.keys()];
const ID_TO_POS = new Map(ID_INDEX.map((id, i) => [id, i]));

export function encodeStack(ids: string[]): string {
  return ids
    .map((id) => ID_TO_POS.get(id))
    .filter((p): p is number => p !== undefined)
    .map((p) => p.toString(36))
    .join(".");
}

export function decodeStack(s: string | null | undefined): string[] {
  if (!s) return [];
  return s
    .split(".")
    .map((tok) => ID_INDEX[parseInt(tok, 36)])
    .filter((id): id is string => !!id);
}

/* ------------------------- artifact helpers ------------------------- */

export function artifactStack(a: Artifact): string[] {
  return a.stack.filter((id) => LEXICON_MAP.has(id));
}

export function findArtifact(id: string): Artifact | undefined {
  return ARTIFACTS.find((a) => a.id === id);
}

/** the primary previewable module of an artifact (first stack chip backed by a module) */
export function artifactPrimaryModule(a: Artifact): string | undefined {
  for (const id of a.stack) {
    const k = LEXICON_MAP.get(id);
    if (k?.module) return k.module;
  }
  // fall back: any module keyword present on the wall family of first chip
  const any = a.stack.map((id) => LEXICON_MAP.get(id)).find((k) => k?.module);
  return any?.module;
}
